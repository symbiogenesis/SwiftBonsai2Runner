//! One paired application request measurement; never an ordinary-suite model run.

use super::*;

const PROFILE: &str = PQ2_ADAPTER_SPEED_PROFILE;
const CASE: &str = PQ2_ADAPTER_SPEED_CASE;
const CAP: u32 = 8;
const PROMPT: &str = "Count from 1 to 100.";
// A second owner must have time to start, execute, and release its Job.
const NEXT_OWNER_RESERVE: Duration = Duration::from_mins(1);
const SERIAL: AdapterProfile = AdapterProfile {
    name: PROFILE,
    case: CASE,
    repacked: false,
    row_workers: 1,
    optional_requests: false,
    required_scale_history: false,
};

fn speed_request() -> Value {
    let mut body = request(json!([{"role":"user","content":PROMPT}]), true, CAP);
    body["enable_thinking"] = json!(false);
    body["abliteration_scale"] = json!(1.3);
    body
}

fn request_rate(summary: &StreamSummary, elapsed: Duration) -> Option<f64> {
    let tokens = u32::try_from(summary.completion_tokens?).ok()?;
    if !(1..=CAP).contains(&tokens) || elapsed.is_zero() {
        return None;
    }
    let rate = f64::from(tokens) / elapsed.as_secs_f64();
    rate.is_finite().then_some(rate)
}

#[expect(
    clippy::redundant_pub_crate,
    reason = "Only the parent harness and its sibling capture module share this test parser."
)]
pub(super) fn visible_output(bytes: &[u8]) -> String {
    let payload = stream_payload(bytes);
    let mut output = String::new();
    for line in std::str::from_utf8(&payload)
        .unwrap()
        .lines()
        .filter_map(|line| line.strip_prefix("data: "))
        .filter(|line| *line != "[DONE]")
    {
        let event: Value = serde_json::from_str(line).unwrap();
        for choice in event["choices"].as_array().unwrap() {
            if let Some(text) = choice["delta"]["content"].as_str() {
                output.push_str(text);
            }
        }
    }
    output
}

async fn measured_stream(port: u16, credential: &str) -> Value {
    // The timer includes connection, request delivery, prefill, generation and
    // complete response framing and connection closure. Parsing and model
    // startup are outside it.
    let started = tokio::time::Instant::now();
    let bytes = exchange(port, credential, &speed_request()).await;
    let elapsed = started.elapsed();
    let summary = streamed_response(&bytes);
    let mut observed = stream_observation(&summary, CAP);
    observed["requestMilliseconds"] = json!(elapsed.as_secs_f64() * 1000.0);
    observed["requestTokensPerSecond"] = json!(request_rate(&summary, elapsed));
    // This public synthetic prompt contains no user conversation or secret.
    // Retain exact generated bytes to reject different-work comparisons.
    observed["visibleContent"] = json!(visible_output(&bytes));
    observed
}

async fn record_measured_request(
    port: u16,
    credential: &str,
    evidence: &Path,
    deadline: tokio::time::Instant,
    report: &mut Value,
    index: usize,
) -> bool {
    let observed = adapter_work_before_cleanup(deadline, measured_stream(port, credential)).await;
    let completed = observed.is_some();
    report["samples"][index]["stream"] = observed.unwrap_or(Value::Null);
    if !completed {
        report["pendingReason"] = json!("request-budget-expired");
    }
    save_acceptance_report(evidence, report);
    completed
}

fn comparison(samples: &[Value]) -> Value {
    let pending = |reason| {
        json!({"status":"pending", "reason":reason,
        "row4OverRow1RequestThroughput":null,"performanceComparisonEligible":false})
    };
    if samples.len() != 2 {
        return pending("incomplete-pair");
    }
    for sample in samples {
        if sample["configuredNativeRowWorkers"] != 1 && sample["configuredNativeRowWorkers"] != 4 {
            return pending("invalid-worker-selection");
        }
        if sample["stream"]["reportedCompletionTokens"] != CAP
            || sample["stream"]["finishReason"] != "length"
            || sample["stream"]["requestTokensPerSecond"]
                .as_f64()
                .is_none_or(|rate| !rate.is_finite() || rate <= 0.0)
            || sample["cleanup"]["ownedJobEmpty"] != true
            || sample["cleanup"]["listenerReleased"] != true
        {
            return pending("missing-matched-length-usage-timing-or-cleanup");
        }
    }
    if samples[0]["configuredNativeRowWorkers"] != 1
        || samples[1]["configuredNativeRowWorkers"] != 4
    {
        return pending("unexpected-pair-order");
    }
    if samples[0]["stream"]["visibleContent"] != samples[1]["stream"]["visibleContent"] {
        return pending("different-generated-content");
    }
    let power_conditions = bonsai_cpu_policy::power::compare_samples(samples);
    let eligible = power_conditions["performanceComparisonEligible"] == true;
    let observed_ratio = samples[1]["stream"]["requestTokensPerSecond"]
        .as_f64()
        .unwrap()
        / samples[0]["stream"]["requestTokensPerSecond"]
            .as_f64()
            .unwrap();
    json!({"status":"measured-single-pair",
        "row4OverRow1RequestThroughput":eligible.then_some(observed_ratio),
        "observedUnqualifiedRequestThroughputRatio":observed_ratio,
        "performanceComparisonEligible":eligible,"powerConditions":power_conditions,
        "fixedOrder":true, "repeatedTrialBenefitQualified":false,
        "completeStateParityQualified":false})
}

async fn paired_requests(
    data: &Path,
    evidence: &Path,
    deadline: tokio::time::Instant,
    report: &mut Value,
) {
    power::begin(report);
    for profile in [&SERIAL, &PQ2_ADAPTER_ROW4_PROFILE] {
        if deadline.saturating_duration_since(tokio::time::Instant::now()) <= NEXT_OWNER_RESERVE {
            report["pendingReason"] = json!("insufficient-next-owner-and-cleanup-reserve");
            save_acceptance_report(evidence, report);
            break;
        }
        let index = report["samples"].as_array().unwrap().len();
        report["samples"].as_array_mut().unwrap().push(json!({
            "configuredNativeRowWorkers":profile.row_workers,
            "rowWorkerCountIndependentlyObserved":false,
            "verifiedReadinessObserved":false, "startupMilliseconds":null,
            "stream":null, "cleanup":null}));
        power::begin(&mut report["samples"][index]);
        report["phase"] = json!(format!("row{}-startup", profile.row_workers));
        save_acceptance_report(evidence, report);
        let started = tokio::time::Instant::now();
        let Some(owner) =
            adapter_work_before_cleanup(deadline, start_adapter(profile, data, evidence)).await
        else {
            report["pendingReason"] = json!("startup-budget-expired");
            power::finish(&mut report["samples"][index]);
            save_acceptance_report(evidence, report);
            break;
        };
        let startup_ms = started.elapsed().as_secs_f64() * 1000.0;
        let port = owner.port();
        let credential = key(&owner);
        let (stop, stopped) = oneshot::channel();
        let running = spawn_local(owner.run(async { stopped.await.map_err(io::Error::other) }));
        report["samples"][index]["startupMilliseconds"] = json!(startup_ms);
        record_worker_readiness(&mut report["samples"][index], profile.row_workers, true);
        report["phase"] = json!(format!("row{}-request", profile.row_workers));
        save_acceptance_report(evidence, report);
        let expired =
            !record_measured_request(port, &credential, evidence, deadline, report, index).await;
        report["phase"] = json!(format!("row{}-cleanup", profile.row_workers));
        save_acceptance_report(evidence, report);
        report["samples"][index]["cleanup"] =
            adapter_owned_stop(stop, running, port, expired).await;
        power::finish(&mut report["samples"][index]);
        save_acceptance_report(evidence, report);
        if expired {
            break;
        }
    }
    report["comparison"] = comparison(report["samples"].as_array().unwrap());
    report["passed"] = json!(report["comparison"]["status"] == "measured-single-pair");
    report["phase"] = json!("completed");
    power::finish(report);
    save_acceptance_report(evidence, report);
}

#[test]
fn native_speed_metric_uses_reported_tokens_and_complete_request_time() {
    let mut summary = StreamSummary {
        finish_reason: "length".to_owned(),
        content_bytes: 3,
        completion_tokens: Some(8),
    };
    assert_eq!(request_rate(&summary, Duration::from_secs(2)), Some(4.0));
    assert_eq!(request_rate(&summary, Duration::ZERO), None);
    summary.completion_tokens = None;
    assert_eq!(request_rate(&summary, Duration::from_secs(2)), None);
    summary.completion_tokens = Some(9);
    assert_eq!(request_rate(&summary, Duration::from_secs(2)), None);
    assert_eq!(speed_request()["max_completion_tokens"], CAP);
    assert_eq!(speed_request()["enable_thinking"], false);
    assert_eq!(speed_request()["abliteration_scale"], 1.3);
}

#[test]
fn native_speed_comparison_requires_matched_output_usage_and_cleanup() {
    let sample = |workers| {
        let power = bonsai_cpu_policy::power::observed_snapshot(Some(true), false, Some(80));
        json!({"configuredNativeRowWorkers":workers,
        "powerBefore":power,"powerAfter":power,
        "stream":{"reportedCompletionTokens":8,"finishReason":"length",
            "requestTokensPerSecond":2.0,"visibleContent":"1 2 3 4"},
        "cleanup":{"ownedJobEmpty":true,"listenerReleased":true}})
    };
    let mut pair = vec![sample(1), sample(4)];
    pair[1]["stream"]["requestTokensPerSecond"] = json!(4.0);
    assert_eq!(comparison(&pair)["row4OverRow1RequestThroughput"], 2.0);
    for observation in [
        Value::Null,
        bonsai_cpu_policy::power::unknown_snapshot(),
        bonsai_cpu_policy::power::observed_snapshot(Some(false), false, Some(79)),
    ] {
        let mut changed = pair.clone();
        changed[1]["powerAfter"] = observation;
        let compared = comparison(&changed);
        assert_eq!(compared["status"], "measured-single-pair");
        assert_eq!(compared["performanceComparisonEligible"], false);
        assert!(compared["row4OverRow1RequestThroughput"].is_null());
        assert_eq!(compared["observedUnqualifiedRequestThroughputRatio"], 2.0);
    }
    for (field, value) in [
        ("reportedCompletionTokens", json!(1)),
        ("finishReason", json!("stop")),
        ("requestTokensPerSecond", Value::Null),
        ("visibleContent", json!("other")),
    ] {
        let mut changed = pair.clone();
        changed[1]["stream"][field] = value;
        assert_eq!(comparison(&changed)["status"], "pending");
        assert!(comparison(&changed)["row4OverRow1RequestThroughput"].is_null());
    }
    pair[1]["cleanup"]["ownedJobEmpty"] = json!(false);
    assert_eq!(comparison(&pair)["status"], "pending");
    assert_eq!(comparison(&[])["status"], "pending");
}

#[test]
fn native_speed_stream_waits_for_complete_framing_and_uses_usage_not_events() {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap();
    runtime.block_on(async {
        timeout(Duration::from_secs(10), async {
            let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
            let port = listener.local_addr().unwrap().port();
            let fixture = tokio::spawn(async move {
                let (peer, _) = listener.accept().await.unwrap();
                let mut peer = BufReader::new(peer);
                let mut length = None;
                loop {
                    let line = prefix_line(&mut peer, 16 * 1024).await;
                    if let Some(value) = line.strip_prefix("Content-Length: ") {
                        length = Some(value.trim().parse::<usize>().unwrap());
                    }
                    if line == "\r\n" {
                        break;
                    }
                }
                let mut body = vec![0; length.unwrap()];
                peer.read_exact(&mut body).await.unwrap();
                assert_eq!(serde_json::from_slice::<Value>(&body).unwrap(), speed_request());
                let payload = concat!(
                    "data: {\"choices\":[{\"delta\":{\"content\":\"1 2 \"},\"finish_reason\":null}]}\n\n",
                    "data: {\"choices\":[{\"delta\":{\"content\":\"3 4\"},\"finish_reason\":null}]}\n\n",
                    "data: {\"choices\":[{\"delta\":{},\"finish_reason\":\"length\"}],\"usage\":{\"completion_tokens\":8}}\n\n",
                    "data: [DONE]\n\n"
                );
                let response = format!(
                    "HTTP/1.1 200 OK\r\nTransfer-Encoding: chunked\r\n\r\n{:X}\r\n{payload}\r\n", payload.len());
                peer.get_mut().write_all(response.as_bytes()).await.unwrap();
                // Terminal usage and DONE alone do not finish the HTTP frame.
                tokio::time::sleep(Duration::from_millis(20)).await;
                peer.get_mut().write_all(b"0\r\n\r\n").await.unwrap();
                peer.get_mut().shutdown().await.unwrap();
            });
            let measured = measured_stream(port, "public-fixture-key").await;
            fixture.await.unwrap();
            assert_eq!(measured["reportedCompletionTokens"], 8);
            assert_eq!(measured["visibleContent"], "1 2 3 4");
            assert!(measured["requestMilliseconds"].as_f64().unwrap() >= 20.0);
            assert!(measured["requestTokensPerSecond"].as_f64().unwrap() <= 400.0);
        }).await.unwrap();
    });
}

#[test]
fn native_speed_partial_pair_survives_cancelled_second_request() {
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap();
    runtime.block_on(async {
        timeout(Duration::from_secs(10), async {
            let evidence = env::temp_dir().join(format!("Bonsai-Speed-Partial-{}-{}",
                std::process::id(), std::time::SystemTime::now()
                    .duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()));
            fs::create_dir(&evidence).unwrap();
            let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
            let port = listener.local_addr().unwrap().port();
            let fixture = tokio::spawn(async move {
                for step in 0..2 {
                    let (peer, _) = listener.accept().await.unwrap();
                    let mut peer = BufReader::new(peer);
                    let mut length = None;
                    loop {
                        let line = prefix_line(&mut peer, 16 * 1024).await;
                        if let Some(value) = line.strip_prefix("Content-Length: ") {
                            length = Some(value.trim().parse::<usize>().unwrap());
                        }
                        if line == "\r\n" { break; }
                    }
                    let mut body = vec![0; length.unwrap()];
                    peer.read_exact(&mut body).await.unwrap();
                    if step == 0 {
                        let payload = concat!(
                            "data: {\"choices\":[{\"delta\":{\"content\":\"1 2 3 4\"},\"finish_reason\":null}]}\n\n",
                            "data: {\"choices\":[{\"delta\":{},\"finish_reason\":\"length\"}],\"usage\":{\"completion_tokens\":8}}\n\n",
                            "data: [DONE]\n\n"
                        );
                        let response = format!("HTTP/1.1 200 OK\r\nTransfer-Encoding: chunked\r\n\r\n{:X}\r\n{payload}\r\n0\r\n\r\n", payload.len());
                        peer.get_mut().write_all(response.as_bytes()).await.unwrap();
                        peer.get_mut().shutdown().await.unwrap();
                    } else {
                        // The deadline must drop the in-flight second connection.
                        assert_eq!(peer.read(&mut [0]).await.unwrap(), 0);
                    }
                }
            });
            let deadline = tokio::time::Instant::now() + STOP_WAIT + Duration::from_secs(2);
            let mut report = json!({"passed":false,"samples":[{"configuredNativeRowWorkers":1},
                {"configuredNativeRowWorkers":4}]});
            assert!(record_measured_request(port, "fixture", &evidence, deadline, &mut report, 0).await);
            // Compare persisted receipts on both sides. Parsing a measured f64
            // can round by one ULP; that does not mean a later write changed it.
            let first: Value = serde_json::from_slice(&fs::read(evidence.join("acceptance.json")).unwrap()).unwrap();
            let first = first["samples"][0].clone();
            assert!(!record_measured_request(port, "fixture", &evidence, deadline, &mut report, 1).await);
            fixture.await.unwrap();
            let saved: Value = serde_json::from_slice(&fs::read(evidence.join("acceptance.json")).unwrap()).unwrap();
            assert_eq!(saved["samples"][0], first);
            assert_eq!(saved["samples"][0]["stream"]["reportedCompletionTokens"], 8);
            assert!(saved["samples"][1]["stream"].is_null());
            assert_eq!(saved["pendingReason"], "request-budget-expired");
            assert_eq!(saved["passed"], false);
            assert_eq!(comparison(saved["samples"].as_array().unwrap())["status"], "pending");
            fs::remove_file(evidence.join("acceptance.json")).unwrap();
            fs::remove_dir(&evidence).unwrap();
        }).await.unwrap();
    });
}

#[test]
fn native_speed_profile_shares_deadline_and_rejects_extra_workloads() {
    assert_eq!(profile_case(PROFILE, false, false), Some(CASE));
    assert_eq!(profile_case(PROFILE, true, false), None);
    assert_eq!(profile_case(PROFILE, false, true), None);
    let runtime = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap();
    runtime.block_on(async {
        tokio::time::pause();
        let deadline = tokio::time::Instant::now() + STOP_WAIT;
        let mut started = false;
        assert_eq!(
            adapter_work_before_cleanup(deadline, async {
                started = true;
            })
            .await,
            None
        );
        assert!(!started);
        assert_eq!(
            deadline.saturating_duration_since(tokio::time::Instant::now()),
            STOP_WAIT
        );
    });
}

